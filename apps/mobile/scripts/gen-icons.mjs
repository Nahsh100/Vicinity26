/**
 * Builds src/components/ui/icons.generated.ts from Material Symbols (Outlined, weight 400), the icon
 * set used by the Stitch designs. Only icons referenced in the app (and category icons from the API
 * seed) are included, as SVG path data rendered with react-native-svg on iOS, Android and web.
 *
 *   node scripts/gen-icons.mjs
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const require = createRequire(import.meta.url);
const pkg = dirname(require.resolve('@material-symbols/svg-400/package.json'));
const dir = join(pkg, 'outlined');

/** Old Material Icons names used in code or data -> Material Symbols name. */
export const ALIASES = {
  favorite_border: 'favorite',
  expand_less: 'keyboard_arrow_up',
  expand_more: 'keyboard_arrow_down',
  place: 'location_on',
  phone_iphone: 'mobile',
  star_border: 'star',
  notifications_none: 'notifications',
  person_outline: 'person',
  mail_outline: 'mail',
  lock_outline: 'lock',
  error_outline: 'error',
  help_outline: 'help',
};

function walk(d, out = []) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx?|mjs)$/.test(f) && !f.includes('icons.generated')) out.push(p);
  }
  return out;
}

const sources = [...walk(join(root, 'src')), join(root, '..', 'api', 'prisma', 'categories.ts')];
const names = new Set(Object.values(ALIASES));
for (const file of sources) {
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(/['"`]([a-z][a-z0-9_]{1,40})['"`]/g)) names.add(ALIASES[m[1]] ?? m[1]);
}
names.add('category');

const paths = (file) => [...readFileSync(file, 'utf8').matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
const icons = {};
for (const n of [...names].sort()) {
  const svgName = n.replace(/_/g, '_');
  const o = join(dir, `${svgName}.svg`);
  if (!existsSync(o)) continue;
  const f = join(dir, `${svgName}-fill.svg`);
  icons[n] = [paths(o), existsSync(f) ? paths(f) : paths(o)];
}

const out = `// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.
// viewBox "0 -960 960 960"; each entry is [outlined, filled].
export const ICONS: Record<string, readonly [string, string]> = ${JSON.stringify(icons, null, 0).replace(/\],"/g, '],\n  "')};

export const ICON_ALIASES: Record<string, string> = ${JSON.stringify(ALIASES)};
`;
writeFileSync(join(root, 'src', 'components', 'ui', 'icons.generated.ts'), out);
console.log(`icons: ${Object.keys(icons).length}`);
