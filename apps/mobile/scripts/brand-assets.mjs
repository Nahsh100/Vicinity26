// Generates the native app icons, splash and notification icon from the brand SVGs in
// assets/brand (supplied by the designer). Re-run after changing the logo:
//   node scripts/brand-assets.mjs
// Web favicons and PWA icons in public/ are the designer's ready-made kit and are copied as-is.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brand = (f) => readFileSync(join(root, 'assets', 'brand', f));
const out = (f) => join(root, 'assets', f);
const S = 1024;

/** Light app-tile background (same gradient as vicinity-app-light.svg), full bleed: stores apply their own mask. */
const lightBg = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#FFFFFF"/><stop offset="1" stop-color="#E2F6F1"/></linearGradient></defs><rect width="${S}" height="${S}" fill="url(#g)"/></svg>`,
);

const render = (svg, size) => sharp(svg, { density: 600 }).resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();

/** Places a mark centred on a canvas at `scale` of its width. */
async function composite(markSvg, scale, background) {
  const size = Math.round(S * scale);
  const mark = await render(markSvg, size);
  const base = background
    ? sharp(background).resize(S, S)
    : sharp({ create: { width: S, height: S, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } });
  return base.composite([{ input: mark, gravity: 'centre' }]).png();
}

// iOS / default icon: no transparency allowed, so the light tile is flattened under the mark.
const iconRgba = await (await composite(brand('vicinity-symbol-small-light.svg'), 0.7, lightBg)).toBuffer();
await sharp(iconRgba).flatten({ background: '#FFFFFF' }).removeAlpha().png().toFile(out('icon.png'));
// Android adaptive icon: the launcher crops to the inner ~66%, so the mark sits well inside it.
await (await composite(brand('vicinity-symbol-small-light.svg'), 0.56)).toFile(out('android-icon-foreground.png'));
await sharp(lightBg).png().toFile(out('android-icon-background.png'));
// Android 13+ themed icons use only the alpha channel of a one-colour mark.
await (await composite(brand('vicinity-black.svg'), 0.56)).toFile(out('android-icon-monochrome.png'));
// Splash: the detailed light symbol on a white screen.
await (await composite(brand('vicinity-symbol-light.svg'), 0.9)).toFile(out('splash-icon.png'));
// Android notification icon: white silhouette on transparent (the system tints it).
await sharp(await render(brand('vicinity-white.svg'), 96)).png().toFile(out('notification-icon.png'));
// Fallback favicon for tools that read app.json (the web app uses public/favicon.*).
await sharp(await render(brand('vicinity-symbol-small-light.svg'), 196)).png().toFile(out('favicon.png'));

// Web home-screen icons match the native app icon (light tile). The browser-tab favicon
// (public/favicon.ico/.svg) stays the designer's version, made to read on light and dark tabs.
const pub = (f) => join(root, 'public', f);
const tile = (size) => sharp(iconRgba).flatten({ background: '#FFFFFF' }).removeAlpha().resize(size, size).png();
await tile(180).toFile(pub('apple-touch-icon.png'));
await tile(192).toFile(pub('icon-192.png'));
await tile(512).toFile(pub('icon-512.png'));
// Maskable: browsers crop to a circle of 80% diameter, so the mark is smaller.
await sharp(await (await composite(brand('vicinity-symbol-small-light.svg'), 0.56, lightBg)).toBuffer())
  .flatten({ background: '#FFFFFF' })
  .removeAlpha()
  .resize(512, 512)
  .png()
  .toFile(pub('maskable-512.png'));

// Social share preview (WhatsApp, Facebook, X): the stacked light lockup with its tagline.
const lockup = await sharp(brand('vicinity-lockup-light.svg'), { density: 300 }).resize({ height: 560 }).png().toBuffer();
await sharp({ create: { width: 1200, height: 630, channels: 3, background: '#FFFFFF' } })
  .composite([{ input: lockup, gravity: 'centre' }])
  .png()
  .toFile(pub('og-image.png'));

// In-app marks as SVG strings (Metro does not import .svg files): rendered with react-native-svg.
const svgString = (f) => brand(f).toString('utf8').replace(/<title>[^<]*<\/title>/, '').trim();
const marks = {
  SYMBOL_LIGHT: 'vicinity-symbol-light.svg',
  SYMBOL_SMALL_LIGHT: 'vicinity-symbol-small-light.svg',
  SYMBOL_DARK: 'vicinity-symbol-dark.svg',
  SYMBOL_SMALL_DARK: 'vicinity-symbol-small-dark.svg',
  LOCKUP_LIGHT: 'vicinity-lockup-light.svg',
  LOCKUP_DARK: 'vicinity-lockup-dark.svg',
};
const ts = [
  '// Generated by scripts/brand-assets.mjs from assets/brand/*.svg. Do not edit.',
  ...Object.entries(marks).map(([k, f]) => `export const ${k} = ${JSON.stringify(svgString(f))};`),
  '',
].join('\n');
writeFileSync(join(root, 'src', 'components', 'brand', 'marks.generated.ts'), ts);

console.log('brand assets written to assets/, public/ and src/components/brand/');
